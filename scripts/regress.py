#!/usr/bin/env python3
"""Regression runner.

Builds the clean testbench, runs every (test, seed) job of a regression list in
parallel, merges functional coverage across runs and writes:

  reports/regression_summary.md    pass/fail, transaction counts, per-test stats
  reports/coverage_matrix.md       bin x test functional coverage matrix
  reports/coverage_convergence.svg coverage vs. transactions, random vs. mixed
  reports/regression_results.json  machine-readable results

Exit status is non-zero if any run fails or planned coverage is not closed.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import subprocess
import sys
import time
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, build, fmt_count, group_of, load_cov, run_sim  # noqa: E402
from svgchart import line_chart  # noqa: E402

ABBREV = {
    "ddr_smoke_test": "smoke", "ddr_rand_test": "mixed", "ddr_soak_test": "soak",
    "ddr_random_only_test": "random", "ddr_row_hit_test": "rowhit",
    "ddr_bank_conflict_test": "conflict", "ddr_hazard_test": "hazard", "ddr_b2b_test": "b2b",
    "ddr_refresh_test": "refresh", "ddr_row_alias_test": "alias", "ddr_corner_test": "corner",
}


def expand(jobs_cfg):
    jobs = []
    for j in jobs_cfg["jobs"]:
        for i in range(j["seeds"]):
            jobs.append({"test": j["test"], "seed": j.get("seed_base", 1) + i, "num_txn": j.get("num_txn")})
    return jobs


def tool_versions():
    v = subprocess.run(["verilator", "--version"], capture_output=True, text=True).stdout.strip()
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                             text=True).stdout.strip()
    except OSError:
        sha = "?"
    return v, sha


def merge(results):
    total = {}
    per_test = defaultdict(lambda: defaultdict(int))
    for r in results:
        if not r.cov_file:
            continue
        bins = load_cov(ROOT / r.cov_file)
        for k, v in bins.items():
            total[k] = total.get(k, 0) + v
            per_test[r.test][k] += v
    return total, per_test


def convergence(results, test):
    runs = sorted([r for r in results if r.test == test and r.cov_file], key=lambda r: r.seed)
    acc, pts, txns = {}, [(0, 0.0)], 0
    for r in runs:
        for k, v in load_cov(ROOT / r.cov_file).items():
            acc[k] = acc.get(k, 0) + v
        txns += r.requests
        pts.append((txns, 100.0 * sum(1 for v in acc.values() if v) / len(acc)))
    return pts


def write_reports(results, det, cfg_name, wall, out):
    out.mkdir(parents=True, exist_ok=True)
    vver, sha = tool_versions()
    total, per_test = merge(results)
    n_bins = len(total)
    n_hit = sum(1 for v in total.values() if v)
    n_pass = sum(r.passed for r in results)
    n_txn = sum(r.requests for r in results)
    n_rd = sum(r.reads_ok for r in results)
    n_cyc = sum(r.end_cycle for r in results)
    cpu = sum(r.wall_s for r in results)
    now = dt.datetime.now().strftime("%Y-%m-%d %H:%M")

    by_test = defaultdict(list)
    for r in results:
        by_test[r.test].append(r)

    # ---------------- regression summary
    s = [f"# Regression Summary", "",
         f"Generated by `scripts/regress.py` ({cfg_name}) on {now}, commit `{sha}`, {vver}, "
         f"Accellera UVM 2020.3.1, host {platform.machine()}.", "",
         "| Metric | Value |", "|---|---|",
         f"| Runs | {len(results)} ({n_pass} passed, {len(results) - n_pass} failed) |",
         f"| Host requests accepted and checked | **{n_txn:,}** |",
         f"| Read data comparisons | {n_rd:,} |",
         f"| Simulated cycles | {n_cyc:,} |",
         f"| Functional coverage | **{n_hit}/{n_bins} planned bins ({100.0 * n_hit / n_bins:.1f}%)** |",
         f"| Wall time | {wall:.0f} s on {os.cpu_count()} cores ({cpu:.0f} s simulator time) |"]
    if det:
        s.append(f"| Reproducibility | {det} |")
    s += ["", "## Per test", "",
          "| Test | Seeds | Passed | Requests | Read checks | Cycles | Coverage (merged seeds) |",
          "|---|---|---|---|---|---|---|"]
    for t in sorted(by_test, key=lambda t: -sum(r.requests for r in by_test[t])):
        rs = by_test[t]
        cov = per_test.get(t, {})
        cpct = 100.0 * sum(1 for v in cov.values() if v) / max(1, len(cov))
        s.append(f"| `{t}` | {len(rs)} | {sum(r.passed for r in rs)}/{len(rs)} | "
                 f"{sum(r.requests for r in rs):,} | {sum(r.reads_ok for r in rs):,} | "
                 f"{sum(r.end_cycle for r in rs):,} | {cpct:.1f}% |")
    fails = [r for r in results if not r.passed]
    s += ["", "## Failures", ""]
    if not fails:
        s.append("None.")
    for r in fails:
        fe = r.first_error or {}
        s.append(f"- `{r.test}` seed {r.seed}: [{fe.get('id')}] cycle {fe.get('cycle')}: "
                 f"{fe.get('message', 'no TEST PASSED marker')} (`{r.log}`)")
    s += ["", "<details><summary>All runs</summary>", "",
          "| Test | Seed | Result | Requests | Cycles | Coverage | Wall (s) |", "|---|---|---|---|---|---|---|"]
    for r in sorted(results, key=lambda r: (r.test, r.seed)):
        s.append(f"| `{r.test}` | {r.seed} | {'PASS' if r.passed else 'FAIL'} | {r.requests:,} | "
                 f"{r.end_cycle:,} | {r.coverage_pct:.1f}% | {r.wall_s} |")
    s += ["", "</details>", "",
          "Reproduce any run with `make run TEST=<test> SEED=<seed>` (add `NUM_TXN=<n>` "
          "if the list overrides it)."]
    (out / "regression_summary.md").write_text("\n".join(s) + "\n")

    # ---------------- coverage matrix
    tests = [t for t in ABBREV if t in per_test] + sorted(t for t in per_test if t not in ABBREV)
    groups = []
    for k in total:
        g = group_of(k)
        if g not in groups:
            groups.append(g)
    random_only = per_test.get("ddr_random_only_test", {})
    c = ["# Functional Coverage Matrix", "",
         f"Merged from {len(results)} regression runs ({n_txn:,} host requests) on {now}, commit `{sha}`.", "",
         f"**Closure: {n_hit}/{n_bins} planned bins ({100.0 * n_hit / n_bins:.1f}%).** "
         "Every planned bin is reachable by design; none are excluded.", "",
         "## Closure by group", "", "| Group | Bins | Hit | Closure | Hit by pure random |", "|---|---|---|---|---|"]
    for g in groups:
        ks = [k for k in total if group_of(k) == g]
        h = sum(1 for k in ks if total[k])
        hr = sum(1 for k in ks if random_only.get(k, 0)) if random_only else 0
        c.append(f"| `{g}` | {len(ks)} | {h} | {100.0 * h / len(ks):.0f}% | {hr}/{len(ks)} |")
    c += ["", "## Bin x test matrix", "",
          "Cells are hit counts summed over all seeds of a test (`·` = never hit). "
          "Column key: " + ", ".join(f"**{ABBREV.get(t, t)}** = `{t}`" for t in tests) + ".", ""]
    for g in groups:
        c += [f"### `{g}`", "", "| Bin | Total | " + " | ".join(ABBREV.get(t, t) for t in tests) + " |",
              "|---|---:|" + "---:|" * len(tests)]
        for k in [k for k in total if group_of(k) == g]:
            cells = [fmt_count(per_test[t].get(k, 0)) if per_test[t].get(k, 0) else "·" for t in tests]
            name = k.split(".", 1)[1]
            mark = "" if total[k] else " **HOLE**"
            c.append(f"| `{name}`{mark} | {fmt_count(total[k])} | " + " | ".join(cells) + " |")
        c.append("")
    if random_only:
        only_directed = [k for k in total if total[k] and not random_only.get(k, 0)]
        c += ["## Bins that pure constrained-random traffic never reached", "",
              f"{len(only_directed)} bins were hit only by the directed-random sequences "
              "(`ddr_random_only_test` never reached them):", ""]
        c += [f"- `{k}`" for k in only_directed]
        c.append("")
    (out / "coverage_matrix.md").write_text("\n".join(c) + "\n")

    # ---------------- convergence chart
    series = []
    if any(r.test == "ddr_random_only_test" for r in results):
        series.append(("pure constrained-random", convergence(results, "ddr_random_only_test")))
    if any(r.test == "ddr_rand_test" for r in results):
        series.append(("mixed directed-random", convergence(results, "ddr_rand_test")))
    if series:
        (out / "coverage_convergence.svg").write_text(
            line_chart(series, "Functional coverage closure", "host requests (merged across seeds)",
                       "planned bins hit (%)", ymin=50, ymax=100))

    (out / "regression_results.json").write_text(json.dumps({
        "generated": now, "commit": sha, "verilator": vver, "list": cfg_name,
        "runs": [r.to_dict() for r in results], "coverage": total, "determinism": det}, indent=1))
    return n_pass == len(results), n_hit == n_bins, n_txn, n_hit, n_bins


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--list", default="regression/regress_list.json")
    ap.add_argument("--quick", action="store_true", help="use regression/quick_list.json")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--out", default="out/regress")
    ap.add_argument("--reports", default="reports")
    ap.add_argument("--no-build", action="store_true")
    args = ap.parse_args()
    lst = "regression/quick_list.json" if args.quick else args.list
    cfg = json.loads((ROOT / lst).read_text())

    if not args.no_build:
        build(None, quiet=False)
    jobs = expand(cfg)
    # longest jobs first
    jobs.sort(key=lambda j: -(j["num_txn"] or 5000))
    out = ROOT / args.out
    print(f"running {len(jobs)} jobs from {lst} with {args.jobs} workers")
    t0 = time.time()
    results = []
    with ThreadPoolExecutor(max_workers=args.jobs) as ex:
        futs = {ex.submit(run_sim, j["test"], j["seed"], out / f"{j['test']}_s{j['seed']}",
                          None, j["num_txn"]): j for j in jobs}
        for f in as_completed(futs):
            r = f.result()
            results.append(r)
            status = "PASS" if r.passed else f"FAIL [{(r.first_error or {}).get('id')}]"
            print(f"  [{len(results):3d}/{len(jobs)}] {r.test:24s} seed {r.seed:5d}  {status:22s} "
                  f"{r.requests:7d} req  cov {r.coverage_pct:5.1f}%  {r.wall_s:6.1f}s", flush=True)

    det = None
    if "determinism_check" in cfg:
        d = cfg["determinism_check"]
        orig = next((r for r in results if r.test == d["test"] and r.seed == d["seed"]), None)
        if orig:
            again = run_sim(d["test"], d["seed"], out / "determinism", None, None)
            same_cov = load_cov(ROOT / orig.cov_file) == load_cov(ROOT / again.cov_file)
            same = same_cov and (orig.requests, orig.reads_ok, orig.end_cycle) == \
                (again.requests, again.reads_ok, again.end_cycle)
            det = (f"`{d['test']}` seed {d['seed']} re-run: "
                   f"{'identical' if same else 'DIFFERENT'} (requests, read checks, end cycle "
                   f"{again.end_cycle:,}, all coverage bins)")
            print("determinism:", det)

    wall = time.time() - t0
    ok_runs, ok_cov, n_txn, n_hit, n_bins = write_reports(results, det, lst, wall, ROOT / args.reports)
    print(f"\n{sum(r.passed for r in results)}/{len(results)} runs passed, {n_txn:,} requests checked, "
          f"coverage {n_hit}/{n_bins} bins, {wall:.0f}s. Reports in {args.reports}/")
    sys.exit(0 if ok_runs and (ok_cov or args.quick) else 1)


if __name__ == "__main__":
    main()
